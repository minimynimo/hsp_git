import argparse
import json
from pathlib import Path
import numpy as np
import pandas as pd
from tqdm import tqdm

def file_name(input_num, total_len):
    return str(input_num).zfill(total_len)

def load_data_for_basin(file_num):
    varssim_dir = "/data0/funato/hsp/2_MERV/varssim_HBV"
    df = pd.read_csv(f"{varssim_dir}/varssim{file_name(file_num, 3)}.csv")
    df['Date'] = pd.to_datetime(df['Date'])
    df.set_index('Date', inplace=True)
    return df

def main():
    parser = argparse.ArgumentParser(description="Verify scaler values for a given run directory.")
    parser.add_argument('--run_dir', type=str, required=True, help='Path to the trained model run directory.')
    args = parser.parse_args()
    
    run_dir = Path(args.run_dir)
    
    # 1. Load the scalers.json file from the specified run directory
    scaler_file = run_dir / 'scalers.json'
    if not scaler_file.exists():
        print(f"ERROR: 'scalers.json' not found in {run_dir}")
        return
        
    with open(scaler_file, 'r') as fp:
        saved_scalers = json.load(fp)
    
    print(f"Successfully loaded scalers from {scaler_file}")
    
    # 2. Load the corresponding cfg.json to get the training period
    cfg_file = run_dir / 'cfg.json'
    if not cfg_file.exists():
        print(f"ERROR: 'cfg.json' not found in {run_dir}")
        return
        
    with open(cfg_file, 'r') as fp:
        cfg = json.load(fp)
        
    train_start = pd.to_datetime(cfg['train_start'])
    train_end = pd.to_datetime(cfg['train_end'])
    
    print(f"Training period from config: {train_start.date()} to {train_end.date()}")

    # 3. Recalculate the TRUE global scalers from scratch
    print("\nRecalculating TRUE global scalers from raw data...")
    dyn_cols = ['Precip', 'PET', 'Temp']
    q_col = 'Obs flow'
    all_dyn_data, all_q_data = [], []

    # Assuming GB location for basin count
    basins = list(map(str, range(1, 397)))

    for basin in tqdm(basins, desc="Loading raw data for verification"):
        df = load_data_for_basin(int(basin))
        df_period = df.loc[train_start:train_end]
        all_dyn_data.append(df_period[dyn_cols])
        all_q_data.append(df_period[[q_col]])

    dyn_df = pd.concat(all_dyn_data)
    q_df = pd.concat(all_q_data)
    
    true_scalers = {
        'dynamic_means': dyn_df.mean().values,
        'dynamic_stds': dyn_df.std().values,
        'q_mean': q_df.mean().values[0],
        'q_std': q_df.std().values[0]
    }
    
    print("TRUE global scalers calculated successfully.")
    
    # 4. Compare the saved scalers with the true scalers
    print("\n--- COMPARISON ---")
    
    is_match = True
    
    print("\nDynamic Means (Precip, PET, Temp):")
    print(f"  Saved in file: {np.array(saved_scalers['dynamic_means'])}")
    print(f"  True values  : {true_scalers['dynamic_means']}")
    if not np.allclose(saved_scalers['dynamic_means'], true_scalers['dynamic_means']):
        is_match = False
        print("  --> MISMATCH!")
        
    print("\nDynamic Stds (Precip, PET, Temp):")
    print(f"  Saved in file: {np.array(saved_scalers['dynamic_stds'])}")
    print(f"  True values  : {true_scalers['dynamic_stds']}")
    if not np.allclose(saved_scalers['dynamic_stds'], true_scalers['dynamic_stds']):
        is_match = False
        print("  --> MISMATCH!")
        
    print("\nQ Mean (Obs flow):")
    print(f"  Saved in file: {saved_scalers['q_mean']}")
    print(f"  True values  : {true_scalers['q_mean']}")
    if not np.allclose(saved_scalers['q_mean'], true_scalers['q_mean']):
        is_match = False
        print("  --> MISMATCH!")
        
    print("\nQ Std (Obs flow):")
    print(f"  Saved in file: {saved_scalers['q_std']}")
    print(f"  True values  : {true_scalers['q_std']}")
    if not np.allclose(saved_scalers['q_std'], true_scalers['q_std']):
        is_match = False
        print("  --> MISMATCH!")
        
    print("\n--- CONCLUSION ---")
    if is_match:
        print("✅ The 'scalers.json' file is CORRECT. The problem may lie elsewhere.")
    else:
        print("❌ The 'scalers.json' file is INCORRECT and was generated by an old training script.")
        print("   This mismatch is the cause of your inaccurate results.")
        print("   SOLUTION: Delete this run directory completely and re-train using the latest main_xgb.py script.")

if __name__ == "__main__":
    main()
